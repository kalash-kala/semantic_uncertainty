import os
import json
import random
import time
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer# Seeded RNG for reproducible randomisation
rng = random.Random(42)

def generate_options(model, tokenizer, question, true_answer, generated, accuracy):
    prompt = f"""You are an expert at creating 4-option multiple choice questions.
For the question below, generate exactly 4 options.

Question: {question}
"""

    if accuracy == 1.0:
        prompt += f"""
The correct answer is: {true_answer}.
Out of the 4 options:
- Exactly 1 option must be this correct answer. Set its "type" to "correct".
- The other 3 options must be plausibly associated but incorrect options. Set their "type" to "associated".
"""
    else:
        prompt += f"""
The correct answer is: {true_answer}.
Another incorrect answer previously generated by a model was: {generated}.
Out of the 4 options:
- Exactly 1 option must be the correct answer: {true_answer}. Set its "type" to "correct".
- Exactly 1 option must be the previously generated incorrect answer: {generated}. Set its "type" to "generated".
- The other 2 options must be plausibly associated but incorrect options. Set their "type" to "associated".
"""

    prompt += """
Return the options strictly as a JSON list of exactly 4 objects. Do not include any other text format, explanation, or markdown formatting like ```json.
Each object must have two string keys: "text" and "type".
Example format:
[
  {"text": "Option 1 Text", "type": "associated"},
  {"text": "Option 2 Text", "type": "correct"},
  {"text": "Option 3 Text", "type": "generated"},
  {"text": "Option 4 Text", "type": "associated"}
]
"""
    
    # Retry loop for generation
    for attempt in range(5):
        try:
            messages = [
                {"role": "system", "content": "You output only raw JSON. You must never wrap the output in markdown tags. Do not write ```json."},
                {"role": "user", "content": prompt}
            ]
            
            input_text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
            input_ids = tokenizer(input_text, return_tensors="pt").to("cuda")
            
            outputs = model.generate(
                **input_ids,
                max_new_tokens=512,
                do_sample=True,
                temperature=0.7,
                pad_token_id=tokenizer.eos_token_id
            )
            
            generated_ids = outputs[0][input_ids["input_ids"].shape[-1]:]
            content = tokenizer.decode(generated_ids, skip_special_tokens=True).strip()
            # Failsafe clean for markdown block that LLMs often incorrectly generate
            if content.startswith("```json"):
                content = content[7:]
            if content.startswith("```"):
                content = content[3:]
            if content.endswith("```"):
                content = content[:-3]
            content = content.strip()
            
            options = json.loads(content)
            
            # Validate output is exactly 4 options with text and type
            if isinstance(options, list) and len(options) == 4:
                valid = True
                for opt in options:
                    if not isinstance(opt, dict) or "text" not in opt or "type" not in opt:
                        valid = False
                if valid:
                    return options
                    
            print(f"Invalid format received from Llama: {content}. Retrying...")
        except Exception as e:
            print(f"Generation/Parsing Error ({type(e).__name__}): {e}. Retrying...")
            
    # Raise error instead of fallback if generation completely fails
    raise RuntimeError(f"Failed to generate valid 4 options for question: '{question}' after 5 attempts.")

def process_file(model, tokenizer, input_path, output_path):
    with open(input_path, 'r') as f:
        data = json.load(f)
        
    new_data = []
    if os.path.exists(output_path):
        try:
            with open(output_path, 'r') as f:
                new_data = json.load(f)
        except json.JSONDecodeError:
            pass
            
    start_idx = len(new_data)
    if start_idx >= len(data):
        print(f"Fully processed {input_path} already.")
        return
        
    print(f"Processing {input_path} (Starting at {start_idx}/{len(data)} items)")
    
    for i in range(start_idx, len(data)):
        row = data[i]
        q_clean = row['question']
        # remove "Answer the following question as briefly as possible." if it exists
        q_clean = q_clean.replace("Answer the following question as briefly as possible.\n", "")
        # remove any "question: " prefix so we don't double it
        if q_clean.startswith("question: "):
            q_clean = q_clean[len("question: "):]
            
        gen = row['generated']
        true_answer = row['true_answer']
        acc = row.get('accuracy', 0.0)
        
        q_prefixed = f"question: {q_clean}"

        # Generate 4 options (list of dictionaries) using Llama directly
        options_list = generate_options(model, tokenizer, q_clean, true_answer, gen, acc)
        
        # Randomize the options visually
        rng.shuffle(options_list)
        
        labels = ["A", "B", "C", "D"]
        mcq_options = []
        correct_label = None
        generated_label = None
        
        for idx, opt in enumerate(options_list):
            label = labels[idx]
            mcq_options.append({"label": label, "text": opt["text"]})
            if opt["type"] == "correct":
                correct_label = label
            elif opt["type"] == "generated":
                generated_label = label
                
        # If model returned something weird, guarantee we have valid labels (edge case)
        if correct_label is None:
            correct_label = "A"
            
        if acc != 1.0 and generated_label is None:
            generated_label = "B" if correct_label != "B" else "C"
            
        if acc == 1.0:
            generated_label = correct_label

        mcq_meta = {
            "question": q_prefixed,
            "options": mcq_options,
            "correct_option": correct_label,
            "generated_option": generated_label,
            "accuracy": acc
        }
        
        mcq_question_full = (
            f"{q_prefixed}\n"
            f"A. {mcq_options[0]['text']}\n"
            f"B. {mcq_options[1]['text']}\n"
            f"C. {mcq_options[2]['text']}\n"
            f"D. {mcq_options[3]['text']}"
        )
        
        row_copy = dict(row)
        row_copy['mcq_meta'] = mcq_meta
        row_copy['mcq_question_full'] = mcq_question_full
        
        new_data.append(row_copy)
        
        # Write to JSON file immediately after each sample is added
        with open(output_path, 'w') as f:
            json.dump(new_data, f, indent=4)
            
        print(f"  ... {i+1}/{len(data)} items processed and saved")
        
    print(f"Finished: {output_path}")

def main():
    model_id = "meta-llama/Llama-3.3-70B-Instruct"
    print(f"Loading full model {model_id}...")
    
    model_hf = AutoModelForCausalLM.from_pretrained(
        model_id, 
        device_map="auto", 
        torch_dtype=torch.bfloat16
    )
    tokenizer = AutoTokenizer.from_pretrained(model_id)

    base_dir = "/home/malay/Trust_me_Im_wrong/corpus/jsons"
    out_base_dir = "/home/malay/Trust_me_Im_wrong/corpus/mcq_jsons"
    
    if not os.path.exists(base_dir):
        print(f"Input directory not found: {base_dir}")
        return
        
    os.makedirs(out_base_dir, exist_ok=True)
    
    for folder in sorted(os.listdir(base_dir)):
        folder_path = os.path.join(base_dir, folder)
        if os.path.isdir(folder_path):
            out_folder_path = os.path.join(out_base_dir, folder)
            os.makedirs(out_folder_path, exist_ok=True)
            
            for file in sorted(os.listdir(folder_path)):
                if file.endswith(".json"):
                    input_path = os.path.join(folder_path, file)
                    # Create output file name similar to the binary script
                    out_filename = file.replace(".json", "_4_option_mcq.json")
                    output_path = os.path.join(out_folder_path, out_filename)
                    
                    process_file(model_hf, tokenizer, input_path, output_path)
            print(f"Finished processing folder: {folder}")

if __name__ == '__main__':
    main()
